#[cfg(test)]
mod ipc_tests {
    use super::*;
    use serde_json::{json, Value};
    use tauri::{
        ipc::{CallbackFn, InvokeBody},
        test::{get_ipc_response, mock_builder, INVOKE_KEY},
        webview::InvokeRequest,
    };

    fn call(
        window: &tauri::WebviewWindow<tauri::test::MockRuntime>,
        command: &str,
        body: Value,
    ) -> Result<Value, Value> {
        get_ipc_response(
            window,
            InvokeRequest {
                cmd: command.into(),
                callback: CallbackFn(0),
                error: CallbackFn(1),
                url: "tauri://localhost".parse().unwrap(),
                body: InvokeBody::Json(body),
                headers: Default::default(),
                invoke_key: INVOKE_KEY.into(),
            },
        )
        .map(|body| body.deserialize::<Value>().unwrap())
    }
    #[test]
    fn metadata_commands_round_trip_with_local_permissions() {
        let repo = infrastructure::persistence::SqliteServerRepository::open(std::path::Path::new(
            ":memory:",
        ))
        .unwrap();
        let app = configure(mock_builder())
            .manage(commands::AppState(Ok(Arc::new(
                application::ServerService::new(Arc::new(repo)),
            ))))
            .build(context())
            .unwrap();
        let window = tauri::WebviewWindowBuilder::new(&app, "main", Default::default())
            .build()
            .unwrap();
        assert_eq!(call(&window, "list_servers", json!({})).unwrap(), json!([]));
        let input =
            json!({"name":"Test","host":"example.com","port":22,"username":"ubuntu","notes":null});
        let server = call(&window, "create_server", json!({"input":input})).unwrap();
        let id = server["id"].as_str().unwrap();
        assert_eq!(
            call(&window, "get_server", json!({"id":id})).unwrap(),
            server
        );
        assert_eq!(server["name"], "Test");
        let mut updated = input.clone();
        updated["name"] = json!("Updated");
        assert_eq!(
            call(&window, "update_server", json!({"id":id,"input":updated})).unwrap()["name"],
            "Updated"
        );
        assert_eq!(
            call(&window, "delete_server", json!({"id":id})).unwrap(),
            Value::Null
        );
        assert_eq!(
            call(&window, "get_server", json!({"id":id})).unwrap_err()["code"],
            "NOT_FOUND"
        );
        let mut invalid = input;
        invalid["host"] = json!("a;whoami");
        assert_eq!(
            call(&window, "create_server", json!({"input":invalid})).unwrap_err()["code"],
            "VALIDATION"
        );
        let denied = tauri::WebviewWindowBuilder::new(&app, "other", Default::default())
            .build()
            .unwrap();
        assert!(call(&denied, "list_servers", json!({})).is_err());
    }
    #[test]
    fn initialization_failure_reaches_ui_without_fake_success() {
        let app = configure(mock_builder())
            .manage(commands::AppState(Err(AppError::new(
                ErrorCode::MigrationFailed,
                "Migration failed.",
            ))))
            .build(context())
            .unwrap();
        let window = tauri::WebviewWindowBuilder::new(&app, "main", Default::default())
            .build()
            .unwrap();
        assert_eq!(
            call(&window, "list_servers", json!({})).unwrap_err()["code"],
            "MIGRATION_FAILED"
        );
        assert_eq!(
            call(
                &window,
                "delete_server",
                json!({"id":uuid::Uuid::new_v4().to_string()})
            )
            .unwrap_err()["code"],
            "MIGRATION_FAILED"
        );
    }
}
