fn initialize(app: &tauri::App) -> Result<Arc<application::ServerService>, AppError> {
    let directory = app.path().app_data_dir().map_err(|_| {
        AppError::new(
            ErrorCode::DatabaseUnavailable,
            "Cannot locate the application data directory.",
        )
    })?;
    std::fs::create_dir_all(&directory).map_err(|_| {
        AppError::new(
            ErrorCode::DatabaseUnavailable,
            "Cannot create the application data directory.",
        )
    })?;
    let repository = Arc::new(infrastructure::persistence::SqliteServerRepository::open(
        &directory.join("remotedock.sqlite"),
    )?);
    let keys = Arc::new(application::keys::KeyService::new(
        repository.clone(),
        Arc::new(infrastructure::credentials::OsCredentialStore),
        directory.join("ssh-keys"),
    ));
    keys.cleanup()?;
    let connections = Arc::new(
        application::connection::ConnectionService::new(
            repository.clone(),
            Arc::new(infrastructure::ssh::RealSshTransport),
            Arc::new(infrastructure::credentials::OsCredentialStore),
        )
        .with_keys(keys.clone()),
    );
    let weak = Arc::downgrade(&connections);
    std::thread::spawn(move || loop {
        std::thread::sleep(std::time::Duration::from_secs(10));
        let Some(service) = weak.upgrade() else { break };
        service.expire_idle();
    });
    let provisioning = Arc::new(application::provisioning::ProvisioningService::new(
        connections.clone(),
        repository.clone(),
    )?);
    let mut service = application::ServerService::new(repository).with_connections(connections);
    service.provisioning = Some(provisioning);
    service.keys = Some(keys);
    Ok(Arc::new(service))
}
fn context<R: tauri::Runtime>() -> tauri::Context<R> {
    tauri::generate_context!()
}

